CREATE TABLE CU_IstoricELO (
    CUELO_Id      INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    CUELO_CUCU_Id INT NOT NULL,
    CUELO_Data    DATE NOT NULL,
    CUELO_Clasic  INT NULL,
    CUELO_Rapid   INT NULL,
    CUELO_Blitz   INT NULL,
    CONSTRAINT FK_CU_IstoricELO_Cursant
        FOREIGN KEY (CUELO_CUCU_Id) REFERENCES CU_Cursanti(CUCU_Id)
);

CREATE INDEX IX_CU_IstoricELO_Cursant ON CU_IstoricELO (CUELO_CUCU_Id, CUELO_Data);
